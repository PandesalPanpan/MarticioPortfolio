// Generates the standalone brand files in brand/ from one set of coordinates.
//
// The logo lives in three places by necessity: src/components/Monogram.tsx
// (the site), public/favicon.svg (the tab), and brand/ (external use, e.g.
// a CV, a GitHub org avatar, a business card). This script owns brand/ so
// those exports never drift from the mark.
//
// Run: node scripts/build-brand-assets.mjs

import { mkdirSync, writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';

const INK = '#17171A'; // --ink, light theme
const PAPER = '#FAF9F7'; // --on-ink, light theme

// Identical to the GLYPH paths in src/components/Monogram.tsx.
const GLYPH_PATHS = [
  'M14 8 V40',
  'M14 8 H23 a6.5 6.5 0 0 1 0 13 H14',
  'M14 25 L24 40 L34 25 V40',
];

/** @param {{ stroke: string, box?: string, rx?: number }} opts */
function svg({ stroke, box, rx = 11 }) {
  // Boxed shrinks the glyph to sit inside the container with even padding;
  // the stroke is pre-divided by that scale so both variants read the same.
  const group = box
    ? `  <rect width="48" height="48" rx="${rx}" fill="${box}"/>\n` +
      `  <g fill="none" stroke="${stroke}" stroke-width="${20/3}" stroke-linecap="round" stroke-linejoin="round" transform="translate(9.6 9.6) scale(0.6)">`
    : `  <g fill="none" stroke="${stroke}" stroke-width="4" stroke-linecap="round" stroke-linejoin="round">`;

  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48">\n` +
    `${group}\n` +
    GLYPH_PATHS.map((d) => `    <path d="${d}"/>`).join('\n') +
    `\n  </g>\n</svg>\n`
  );
}

const VARIANTS = [
  {
    name: 'pm-mark-dark',
    svg: svg({ stroke: INK }),
    sizes: [256, 512, 1024],
    note: 'bare mark, dark ink, transparent background',
  },
  {
    name: 'pm-mark-light',
    svg: svg({ stroke: PAPER }),
    sizes: [256, 512, 1024],
    note: 'bare mark, light ink, transparent background (for dark backgrounds)',
  },
  {
    name: 'pm-icon-dark',
    svg: svg({ stroke: PAPER, box: INK }),
    sizes: [16, 32, 64, 128, 256, 512, 1024],
    note: 'boxed app icon, dark square',
  },
  {
    name: 'pm-icon-light',
    svg: svg({ stroke: INK, box: PAPER }),
    sizes: [16, 32, 64, 128, 256, 512, 1024],
    note: 'boxed app icon, light square',
  },
];

mkdirSync('brand', { recursive: true });

const browser = await chromium.launch();
const written = [];

for (const variant of VARIANTS) {
  writeFileSync(`brand/${variant.name}.svg`, variant.svg);
  written.push(`brand/${variant.name}.svg`);

  for (const size of variant.sizes) {
    const page = await browser.newPage({
      viewport: { width: size, height: size },
      deviceScaleFactor: 1,
    });
    await page.setContent(
      `<body style="margin:0">${variant.svg.replace('<svg', `<svg width="${size}" height="${size}"`)}</body>`,
    );
    // omitBackground keeps the bare marks genuinely transparent.
    await page.screenshot({ path: `brand/${variant.name}-${size}.png`, omitBackground: true });
    await page.close();
    written.push(`brand/${variant.name}-${size}.png`);
  }
}

// --- Site icons -----------------------------------------------------------
// iOS ignores SVG favicons entirely, so the home-screen icon has to be a PNG.
// It is drawn square (rx=0) because iOS applies its own corner mask, and
// opaque because a transparent apple-touch-icon renders on a black plate.
const appleIcon = svg({ stroke: PAPER, box: INK, rx: 0 });
const applePage = await browser.newPage({ viewport: { width: 180, height: 180 } });
await applePage.setContent(
  `<body style="margin:0">${appleIcon.replace('<svg', '<svg width="180" height="180"')}</body>`,
);
await applePage.screenshot({ path: 'public/apple-touch-icon.png' });
await applePage.close();
written.push('public/apple-touch-icon.png');

// The tab icon. An SVG favicon can carry its own stylesheet, so the square
// inverts with the browser theme instead of a dark box vanishing into dark
// browser chrome.
const favicon =
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48">\n` +
  `  <!-- Generated by scripts/build-brand-assets.mjs. Do not edit by hand.\n` +
  `       Mirrors the boxed variant of src/components/Monogram.tsx. -->\n` +
  `  <style>\n` +
  `    .box { fill: ${INK}; }\n` +
  `    .mark { stroke: ${PAPER}; }\n` +
  `    @media (prefers-color-scheme: dark) {\n` +
  `      .box { fill: ${PAPER}; }\n` +
  `      .mark { stroke: ${INK}; }\n` +
  `    }\n` +
  `  </style>\n` +
  `  <rect class="box" width="48" height="48" rx="11"/>\n` +
  `  <g class="mark" fill="none" stroke-width="${20/3}" stroke-linecap="round" stroke-linejoin="round" transform="translate(9.6 9.6) scale(0.6)">\n` +
  GLYPH_PATHS.map((d) => `    <path d="${d}"/>`).join('\n') +
  `\n  </g>\n</svg>\n`;
writeFileSync('public/favicon.svg', favicon);
written.push('public/favicon.svg');

await browser.close();
console.log(`Wrote ${written.length} files:\n` + written.map((f) => `  ${f}`).join('\n'));
